/**
 * 内置题面 —— 网站里「已经存在的那道题」的真实文本
 *
 * 为什么要有这个文件：站点那条对话原来只用一句写死的文案告诉智能体
 * 「已上传题目及附件」，并没有真的把题面送出去。要让分析变成**实际生成**的，
 * 就得先把真实题面交给智能体。真题的题面是公开材料，直接内置；
 * 用户自己输入的题目走用户文本（见 resolveCase()）。
 *
 * 逐字转录自 `2026全国数模/C题/C题.pdf`（第 1–3 页），只做了一件事：
 * 去掉 PDF 抽版时错位的标点与断行。**数字一个都没动**。
 *
 * ⚠️ 附件只登记名字、不附内容：站点手上没有可读的附件二进制，
 *    谎报「已读取」会让智能体编造里面的数值。名字照实给，让它自己
 *    按「未读取」处理并在 source_inventory 里如实标出来。
 */

export interface BuiltinAttachment {
  attachment_id: string
  name: string
  media_type: string
}

export interface BuiltinProblem {
  /** 对应原型题库的 id（core.ts 的 PROBLEMS） */
  protoId: string
  /**
   * 分析通道用的题目标识 —— 产物目录与会话映射按它区分。
   * 原先是沙箱侧的映射表（problemMap.ts）提供，该表已随「删掉沙箱预留题目数据」
   * 移除，改为题目自带；取值与原来一致，已有产物照旧读得回来。
   */
  caseId: string
  title: string
  /** 题面正文 —— 原样发给智能体 */
  text: string
  attachments: BuiltinAttachment[]
  /** 题面出处，页内标注用 */
  source: string
}

