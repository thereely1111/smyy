/** 这道题有没有内置题面；没有返回 null */
export function builtinProblem(protoId: string | null | undefined): BuiltinProblem | null {
  if (!protoId) return null
  return BUILTIN[protoId] ?? null
}

/** 已登记内置题面的题号 —— 只有这些真题会走「实际生成」通道 */
export function builtinProblemIds(): string[] {
  return Object.keys(BUILTIN)
}
