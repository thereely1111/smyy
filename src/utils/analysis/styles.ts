/**
 * 分析通道自带的三张样式表：对话流 / 产物卡 / 报告卡。
 *
 * 为什么要有这么一层（2026-10-12）：
 *   这三张表原来各由自己的渲染函数**懒注入** —— 第一次画到它的时候才
 *   `document.head.appendChild`。跑着的时候没问题，可工作台的对话区是**可恢复**的：
 *   页面刷新（或从沙箱返回后组件重建）时，对话区是从任务快照整块 `innerHTML`
 *   贴回来的 —— 那一刻没有任何渲染函数被调用，三张表一张都不在 head 里，
 *   于是快照里那些 `lv-*` / `art-*` / `rep-*` 节点全部掉回浏览器默认样式：
 *   正文没有字号行距、列表没有圆点缩进、折叠的思考过程变成一个裸三角、
 *   工具明细的 pre 变成满屏黑字等宽块……用户看到的就是「对话内容没样式」。
 *   （实测：`#w-steps` / 附件条同时缺席，见 2026-10-12 的取证记录。)
 *
 * 所以由页面外壳在挂载时统一补一次。幂等：三张表各自都带 `id` 去重，
 * 重复调用零副作用。样式本身仍留在各自的模块里（谁用谁维护），这里只管「都挂上」。
 *
 * 2026-10-12 二次修（用户第二次报「对话样式还是缺失」）：**改成入口就挂**。
 *   上次只挂在外壳的 onMounted 里，实测仍不够 —— 外壳挂过一次之后，这份文档里
 *   再没有任何「一定会走到」的注入点；而这份 <style> 自己是**按 id 去重**的，
 *   页面上只要还剩一张**旧版本的**同名表，后面每次注入都会被那句早退挡掉，
 *   于是「新标记 + 旧样式」可以一直错位下去（这正是用户看到的：折叠条变成一个裸三角、
 *   思考中的转圈不见、正文掉回默认字号）。现在两头都收：
 *     · 入口（main.ts）先挂一次 —— 任何入口、任何外壳、任何顺序都跑得到；
 *     · 三张表各自「内容不一致就换掉」，不再认 id 不认内容；
 *     · 外壳 onMounted 那次留着（幂等，零成本）。
 *   为什么这里可以全局挂、而原型那 67K 不行：这三张表的选择器只有 `lv-*` / `art-*` /
 *   `rep-*` 三个前缀（已逐条核对，与沙箱模块零重叠，`.art-view` 那类不在这两张表里）。
 */

import { ensureLiveStyle } from './live'
import { ensureArtifactStyle } from './artifact/render'
import { ensureReportStyle } from './report'

/** 把分析通道的三张样式表都挂到 head（幂等；已经挂对的不动，挂错版本的换掉） */
export function ensureAnalysisStyles(): void {
  /* 一张一张 try：哪张出问题都不该连带另外两张，更不该把调用它的生命周期钩子整段打断
     —— 挂载钩子里这里一抛，后面的 bootPrototype / applyRoute 就都不执行了，页面会半死
     （症状是「顶栏能看见、点哪都不动」，比样式缺失更难查）。 */
  for (const ensure of [ensureLiveStyle, ensureArtifactStyle, ensureReportStyle]) {
    try {
      ensure()
    } catch (e) {
      console.warn('[analysis-styles] 这张表没挂上：', e)
    }
  }
}
